package ru.GreenWill.server.enumarated;

/**
 * Перечисление, представляющее статусы заказа в системе.
 * 
 * <p>Жизненный цикл заказа проходит через следующие статусы:</p>
 * <ul>
 *     <li>{@link #WAITING} - Заказ создан и ожидает принятия поваром</li>
 *     <li>{@link #ACTIVITY} - Заказ принят поваром и находится в процессе приготовления</li>
 *     <li>{@link #GOES} - Заказ приготовлен и готов к доставке</li>
 *     <li>{@link #RUN} - Заказ взят курьером и находится в процессе доставки</li>
 *     <li>{@link #COMPLETED} - Заказ успешно доставлен клиенту</li>
 *     <li>{@link #REJECTED} - Заказ отклонен</li>
 * </ul>
 *
 * @author Даниил Рогозников
 * @version 1.0
 * @since 2024-02-13
 */
public enum Status {
    /** @deprecated Устаревший статус, планируется к удалению */
    @Deprecated
    FINISH,
    
    /** Заказ ожидает принятия поваром */
    WAITING,
    
    /** Заказ в процессе приготовления */
    ACTIVITY,
    
    /** Заказ успешно доставлен */
    COMPLETED,
    
    /** Заказ готов к доставке */
    GOES,
    
    /** Заказ отклонен */
    REJECTED,
    
    /** Заказ в процессе доставки */
    RUN
}
