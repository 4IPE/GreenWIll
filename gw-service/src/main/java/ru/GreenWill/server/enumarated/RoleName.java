package ru.GreenWill.server.enumarated;

/**
 * Перечисление, представляющее роли пользователей в системе.
 *
 * <p>Система поддерживает следующие роли:</p>
 * <ul>
 *     <li>{@link #ROLE_ADMIN} - Администратор системы с полным доступом</li>
 *     <li>{@link #ROLE_USER} - Обычный пользователь (клиент)</li>
 *     <li>{@link #ROLE_COOK} - Повар, отвечающий за приготовление заказов</li>
 *     <li>{@link #ROLE_COURIER} - Курьер, осуществляющий доставку заказов</li>
 * </ul>
 *
 * <p>Каждая роль имеет свой набор прав и ограничений в системе.</p>
 *
 * @author Даниил Рогозников
 * @version 1.0
 * @since 2024-02-13
 */
public enum RoleName {
    /** Администратор с полным доступом к системе */
    ROLE_ADMIN,
    
    /** Обычный пользователь (клиент) */
    ROLE_USER,
    
    /** Повар, ответственный за приготовление */
    ROLE_COOK,
    
    /** Курьер, осуществляющий доставку */
    ROLE_COURIER
}
